"use strict";

// ---------- Club configuration (static, baked-in) ----------
const CLUB = {
  clubName: "Pannonian Padel",
  timezone: "Europe/Zagreb",
  currency: "EUR",
  courts: [
    { id: "5774c0ff-bb9f-4113-852f-aac4167ac4e7", name: "Teren 1", indoor: true },
    { id: "b786943e-34be-442d-8eed-cb7dad9da27c", name: "Teren 2", indoor: true },
    { id: "e77aef34-6aba-47fe-96fa-f0d630efe93d", name: "Teren 3", indoor: true },
    { id: "7552f97d-d1e0-4399-a0c3-ca4c27647eca", name: "Teren 4", indoor: true },
    { id: "a5a1b2fb-3141-4751-b8a5-fda9422d0741", name: "Teren 5", indoor: false },
    { id: "3208e4f9-91d9-4c2c-8785-508460b6b801", name: "Teren 6", indoor: false },
  ],
};

const DURATIONS = [60, 90, 120];
const DEFAULT_PLAYERS = [
  { passSport: true, selected: false },
  { passSport: true, selected: false },
  { passSport: false, selected: false },
  { passSport: false, selected: false },
]; // PassSport: 2 on, 2 off
const MAX_PLAYERS = 6;
const MIN_PLAYERS = 2;

// Price band boundaries (by start time)
const MORNING_END = 12 * 60;   // 12:00
const PEAK_START = 13 * 60 + 30; // 13:30

// ---------- State ----------
let prices = null; // loaded from prices.json (generated by GitHub Action)
let sel = load("padel.sel", null);
let ppl = load("padel.ppl", null) || DEFAULT_PLAYERS.slice();
// Migrate old player objects that didn't have the `selected` grouping flag
ppl.forEach((p) => { if (p.selected == null) p.selected = false; });
let manualPrice = null; // null => auto
let startSteps = 0; // start-time offset in 30-min steps (session only)

// ---------- DOM ----------
const $ = (id) => document.getElementById(id);

// ---------- Helpers ----------
function load(key, fallback) {
  try {
    const v = JSON.parse(localStorage.getItem(key));
    return v === null || v === undefined ? fallback : v;
  } catch {
    return fallback;
  }
}
function save(key, val) {
  try { localStorage.setItem(key, JSON.stringify(val)); } catch {}
}

function round2(n) { return Math.round(n * 100) / 100; }
function fmtEUR(eur) {
  return (Number(eur) || 0).toLocaleString("hr-HR", { minimumFractionDigits: 2, maximumFractionDigits: 2 }) + " €";
}
function fmtEURfromCents(c) { return fmtEUR(c / 100); }

function timeToMin(hhmm) {
  const [h, m] = String(hhmm).split(":").map(Number);
  return (h || 0) * 60 + (m || 0);
}
function minToHHMM(min) {
  min = ((min % 1440) + 1440) % 1440;
  const h = Math.floor(min / 60), m = min % 60;
  return String(h).padStart(2, "0") + ":" + String(m).padStart(2, "0");
}

// ---------- Selection defaults ----------
function ensureSelection() {
  if (!sel || !CLUB.courts.some((c) => c.id === sel.courtId)) {
    sel = { courtId: CLUB.courts[0]?.id || null, durationMin: 90 };
  }
  if (sel.durationMin == null) sel.durationMin = 90;
  save("padel.sel", sel);
}

// ---------- Auto start time ----------
function baseStartMinutes() {
  const ms = Date.now() - sel.durationMin * 60000;
  const rounded = Math.round(ms / 1800000) * 1800000;
  const fmt = new Intl.DateTimeFormat("en-GB", { timeZone: CLUB.timezone, hour: "2-digit", minute: "2-digit", hour12: false });
  return timeToMin(fmt.format(new Date(rounded)));
}
function effectiveStart() {
  return minToHHMM(baseStartMinutes() + startSteps * 30);
}

// ---------- Price (from prices.json + linear transition) ----------
function rateAt(court, hhmm) {
  const p = prices?.courts?.[court.id];
  const morning = p?.morning ?? 20;
  const peak = p?.peak ?? (court.indoor ? 28 : 24);
  const h = timeToMin(hhmm);
  if (h <= MORNING_END) return morning;
  if (h >= PEAK_START) return peak;
  const t = (h - MORNING_END) / (PEAK_START - MORNING_END);
  return round2(morning + (peak - morning) * t);
}

function autoPriceEUR() {
  const court = CLUB.courts.find((c) => c.id === sel.courtId);
  if (!court) return null;
  const rate = rateAt(court, effectiveStart());
  return round2((rate * sel.durationMin) / 60);
}
function currentPriceEUR() {
  return manualPrice != null ? manualPrice : autoPriceEUR();
}

// ---------- Split ----------
function computeSplit() {
  const price = currentPriceEUR();
  const duration = sel.durationMin;
  if (price == null || duration == null || ppl.length === 0) return null;

  const cents = Math.round(price * 100);
  const n = ppl.length;
  const freeFrac = Math.min(1, 60 / duration);

  const rows = ppl.map((p, i) => {
    const base = cents / n;
    const pay = p.passSport ? base * (1 - freeFrac) : base;
    const payC = Math.round(pay);
    return { idx: i + 1, passSport: p.passSport, payCents: payC, savedCents: Math.round(base - payC) };
  });

  const totalPaid = rows.reduce((s, r) => s + r.payCents, 0);
  const totalSaved = rows.reduce((s, r) => s + r.savedCents, 0);
  return { rows, totalPaid, totalSaved, priceCents: cents };
}

// ---------- Render: courts ----------
function renderCourts() {
  const el = $("courts");
  el.innerHTML = "";
  CLUB.courts.forEach((c) => {
    const b = document.createElement("button");
    b.className = "chip court" + (c.id === sel.courtId ? " sel" : "");
    b.innerHTML = `<span>${c.name}</span><span class="badge">${c.indoor ? "zatvoreni" : "vanjski"}</span>`;
    b.onclick = () => {
      if (sel.courtId === c.id) return;
      sel.courtId = c.id;
      manualPrice = null;
      save("padel.sel", sel);
      renderCourts();
      renderResult();
    };
    el.appendChild(b);
  });
}

// ---------- Render: durations ----------
function renderDurations() {
  const el = $("durations");
  el.innerHTML = "";
  DURATIONS.forEach((d) => {
    const b = document.createElement("button");
    b.className = "chip" + (d === sel.durationMin ? " sel" : "");
    b.innerHTML = `<span>${d} min</span>`;
    b.onclick = () => {
      if (sel.durationMin === d) return;
      sel.durationMin = d;
      startSteps = 0;
      manualPrice = null;
      save("padel.sel", sel);
      renderDurations();
      renderStart();
      renderResult();
    };
    el.appendChild(b);
  });
}

// ---------- Render: start time ----------
function renderStart() {
  $("startTime").value = effectiveStart();
}

// ---------- Render: players ----------
function renderPlayers() {
  const el = $("players");
  el.innerHTML = "";
  ppl.forEach((p, i) => {
    const row = document.createElement("div");
    row.className = "player-row";
    row.innerHTML = `
      <span class="pnum">${i + 1}</span>
      <span class="pname">Igrač ${i + 1}</span>
      <label class="switch">
        <input type="checkbox" ${p.passSport ? "checked" : ""} data-pass="${i}" />
        <span class="slider"></span>
      </label>
      <span class="pass-label${p.passSport ? "" : " off"}">PassSport</span>
      ${ppl.length > MIN_PLAYERS ? `<button class="del" data-del="${i}" aria-label="Ukloni igrača">&times;</button>` : ""}`;
    el.appendChild(row);
  });

  el.querySelectorAll('input[data-pass]').forEach((inp) => {
    inp.addEventListener("change", () => {
      ppl[Number(inp.dataset.pass)].passSport = inp.checked;
      save("padel.ppl", ppl);
      renderPlayers();
      renderResult();
    });
  });
  el.querySelectorAll('button[data-del]').forEach((btn) => {
    btn.addEventListener("click", () => {
      ppl.splice(Number(btn.dataset.del), 1);
      save("padel.ppl", ppl);
      renderPlayers();
      renderResult();
    });
  });
}

// ---------- Render: result ----------
function renderResult() {
  const price = currentPriceEUR();
  const input = $("priceInput");
  if (document.activeElement !== input) {
    input.value = price == null ? "" : String(price);
  }

  const el = $("result");
  const split = computeSplit();

  if (!split) {
    el.innerHTML = '<div class="empty">Nema dovoljno podataka za izračun.</div>';
    return;
  }

  const parts = split.rows.map((r) => {
    const p = ppl[r.idx - 1];
    const isSel = p.selected;
    const isFree = r.payCents === 0;
    const disc = r.savedCents > 0 ? `<span class="disc">60 min gratis</span>` : "";
    return `<div class="result-row${isSel ? " selected" : ""}" data-select="${r.idx - 1}" role="button" tabindex="0" aria-pressed="${isSel ? "true" : "false"}" ontouchstart="">
      <div class="who">
        <div class="avatar">${r.idx}</div>
        <div class="nm">Igrač ${r.idx}${r.passSport ? ' <span class="free-note">· PassSport</span>' : ""}</div>
      </div>
      <div class="amount ${isFree ? "free" : ""}">${fmtEURfromCents(r.payCents)}${disc}</div>
      <div class="check" aria-hidden="true">✓</div>
    </div>`;
  }).join("");

  const selectedCents = split.rows
    .filter((r) => ppl[r.idx - 1].selected)
    .reduce((s, r) => s + r.payCents, 0);
  const unselectedCents = split.totalPaid - selectedCents;
  const hasSelection = selectedCents > 0 && selectedCents < split.totalPaid;

  const groupMeta = hasSelection ? `<div class="result-meta group-meta">
      <span>Označeni: <span class="strong">${fmtEURfromCents(selectedCents)}</span></span>
      <span>Neoznačeni: <span class="strong">${fmtEURfromCents(unselectedCents)}</span></span>
    </div>` : "";

  const meta = `<div class="result-meta">
      <span>Ukupno plaćaju: <span class="strong">${fmtEURfromCents(split.totalPaid)}</span></span>
      ${split.totalSaved > 0 ? `<span>PassSport pokriva: <span class="strong">${fmtEURfromCents(split.totalSaved)}</span></span>` : ""}
    </div>`;

  const hint = `<div class="result-hint">Klikni na igrača da ga označiš za grupno plaćanje.</div>`;

  el.innerHTML = parts + groupMeta + meta + hint;

  el.querySelectorAll(".result-row[data-select]").forEach((row) => {
    const toggle = () => {
      const idx = Number(row.dataset.select);
      ppl[idx].selected = !ppl[idx].selected;
      save("padel.ppl", ppl);
      renderResult();
    };
    row.addEventListener("click", toggle);
    row.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") {
        e.preventDefault();
        toggle();
      }
    });
  });
}

// ---------- Events ----------
function bindEvents() {
  const input = $("priceInput");
  input.addEventListener("input", () => {
    if (input.value === "") manualPrice = null;
    else {
      const v = parseFloat(input.value.replace(",", "."));
      manualPrice = Number.isFinite(v) ? v : null;
    }
    renderResult();
  });
  input.addEventListener("focus", () => input.select());

  $("startMinus").onclick = () => { startSteps--; renderStart(); renderResult(); };
  $("startPlus").onclick = () => { startSteps++; renderStart(); renderResult(); };
  $("startTime").addEventListener("change", () => {
    const m = timeToMin($("startTime").value);
    startSteps = Math.round((m - baseStartMinutes()) / 30);
    renderStart();
    renderResult();
  });

  $("addPlayer").onclick = () => {
    if (ppl.length >= MAX_PLAYERS) return;
    ppl.push({ passSport: false, selected: false });
    save("padel.ppl", ppl);
    renderPlayers();
    renderResult();
  };
}

// ---------- Init ----------
async function init() {
  ensureSelection();
  $("clubName").textContent = CLUB.clubName;

  // Prices are a static file (generated by GitHub Action) - no API calls
  try {
    const res = await fetch("./prices.json", { cache: "no-cache" });
    if (res.ok) prices = await res.json();
  } catch {}

  renderCourts();
  renderDurations();
  renderStart();
  renderPlayers();
  renderResult();
  bindEvents();

  if ("serviceWorker" in navigator) {
    navigator.serviceWorker.register("./sw.js").catch(() => {});
  }
}

document.addEventListener("DOMContentLoaded", init);
